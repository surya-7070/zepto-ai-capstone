"""
Module 2, Part A — profiling, cleaning and the data story.

This script performs the ONE AND ONLY load of the raw Titanic dataset for the
whole module:

    * if analytics/titanic.csv already exists (the committed offline fallback),
      it is read from disk with pd.read_csv;
    * otherwise sns.load_dataset('titanic') is called once (this needs internet
      the first time; seaborn caches it afterwards) and the result is
      immediately written to titanic.csv.

Everything downstream — the rest of this script and 02_modeling.py — works from
that same file. `sns.load_dataset('titanic')` is never called a second time.

Outputs
-------
    titanic.csv                  raw dataset, committed offline fallback
    titanic_clean.csv            cleaned dataset produced by Task 2
    figures/*.png                all charts
    reports/01_eda_report.md     every measured number + written interpretation

Run:  python 01_eda.py
"""

from __future__ import annotations

import os
import textwrap

import matplotlib

matplotlib.use("Agg")  # headless-safe
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_RAW = os.path.join(HERE, "titanic.csv")
CSV_CLEAN = os.path.join(HERE, "titanic_clean.csv")
FIG_DIR = os.path.join(HERE, "figures")
REPORT = os.path.join(HERE, "reports", "01_eda_report.md")

CORR_COLS = ["survived", "pclass", "age", "sibsp", "parch", "fare"]

sns.set_theme(style="whitegrid")
pd.set_option("display.width", 120)
pd.set_option("display.max_columns", 30)

md: list[str] = []  # the report is assembled here as we go


def say(text: str = "") -> None:
    """Print to console and append to the markdown report."""
    print(text)
    md.append(text)


def block(df_or_text) -> None:
    say("```")
    say(str(df_or_text))
    say("```")
    say()


def savefig(name: str) -> str:
    os.makedirs(FIG_DIR, exist_ok=True)
    path = os.path.join(FIG_DIR, name)
    plt.tight_layout()
    plt.savefig(path, dpi=110)
    plt.close()
    return f"figures/{name}"


# ===========================================================================
# Task 1 — load once, profile, save the offline fallback
# ===========================================================================
def load_once() -> pd.DataFrame:
    if os.path.exists(CSV_RAW):
        print(f"[load] reading committed offline fallback: {CSV_RAW}")
        return pd.read_csv(CSV_RAW)

    print("[load] titanic.csv not found - calling sns.load_dataset('titanic') "
          "(needs internet the first time; seaborn then caches it)")
    df = sns.load_dataset("titanic")
    df.to_csv(CSV_RAW, index=False)
    print(f"[load] saved offline fallback -> {CSV_RAW}")
    return df


def main() -> int:
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    df = load_once()

    say("# Module 2, Part A — EDA report")
    say()
    say("Auto-generated by `01_eda.py`. Every number below is measured from "
        "the data at run time; the interpretations are authored.")
    say()

    # ---------------------------------------------------------------- Task 1
    say("## Task 1 — profiling")
    say()
    say(f"`df.shape` = **{df.shape}** ({df.shape[0]} rows, {df.shape[1]} columns)")
    say()

    say("### `df.info()`")
    import io

    buf = io.StringIO()
    df.info(buf=buf)
    block(buf.getvalue())

    say("### `df.describe()`")
    block(df.describe().round(3))

    missing_pct = (df.isna().mean() * 100).round(2)
    missing_pct = missing_pct[missing_pct > 0].sort_values(ascending=False)
    say("### Missing values (percentage, columns with any missing)")
    block(missing_pct.to_string())

    # ---------------------------------------------------------------- Task 2
    say("## Task 2 — missing-value handling (threshold rule)")
    say()
    say("Rule applied: **< 5% missing → drop those rows; 5–30% missing → "
        "impute; > 30% missing → imputation is unreliable, so decide "
        "explicitly between dropping the column and encoding \"missing\" as "
        "its own category, with justification.**")
    say()

    clean = df.copy()
    decisions: list[tuple[str, float, str, str]] = []

    for col, pct in missing_pct.items():
        if pct < 5:
            strategy = "drop rows"
            reason = (f"`{col}` is {pct}% missing, which is under the 5% "
                      f"threshold, so the affected rows are dropped — losing "
                      f"this few rows costs essentially no statistical power "
                      f"and avoids inventing values.")
        elif pct <= 30:
            if pd.api.types.is_numeric_dtype(clean[col]):
                strategy = "impute (median)"
                reason = (f"`{col}` is {pct}% missing, inside the 5–30% band, "
                          f"so it is imputed rather than dropped. The median "
                          f"is used instead of the mean because the column is "
                          f"skewed and the median is not dragged by the tail.")
            else:
                strategy = "impute (mode)"
                reason = (f"`{col}` is {pct}% missing, inside the 5–30% band, "
                          f"so it is imputed with its most frequent value.")
        else:
            strategy = "drop column"
            reason = (f"`{col}` is {pct}% missing — far above 30%. Imputing "
                      f"over three quarters of a column would manufacture the "
                      f"column rather than repair it, and the surviving values "
                      f"are not missing at random (they skew to upper-class "
                      f"passengers), so \"missing\" as its own category would "
                      f"mostly encode passenger class, which `pclass` already "
                      f"carries. The column is therefore dropped.")
        decisions.append((col, float(pct), strategy, reason))

    # apply, in a deterministic order: drop columns, impute, then drop rows
    for col, pct, strategy, _ in decisions:
        if strategy == "drop column":
            clean = clean.drop(columns=[col])
        elif strategy == "impute (median)":
            clean[col] = clean[col].fillna(clean[col].median())
        elif strategy == "impute (mode)":
            clean[col] = clean[col].fillna(clean[col].mode().iloc[0])
    row_drop_cols = [c for c, _, s, _ in decisions if s == "drop rows" and c in clean]
    before = len(clean)
    clean = clean.dropna(subset=row_drop_cols)
    dropped = before - len(clean)

    say("| column | % missing | strategy | justification |")
    say("|---|---|---|---|")
    for col, pct, strategy, reason in decisions:
        say(f"| `{col}` | {pct}% | {strategy} | {reason} |")
    say()
    say(f"Rows dropped by the < 5% rule: **{dropped}**. "
        f"Cleaned shape: **{clean.shape}** (was {df.shape}). "
        f"Remaining missing values: **{int(clean.isna().sum().sum())}**.")
    say()

    clean.to_csv(CSV_CLEAN, index=False)
    say(f"Cleaned frame saved to `titanic_clean.csv`.")
    say()

    # ---------------------------------------------------------------- Task 3
    say("## Task 3 — univariate analysis")
    say()

    for col in ["age", "fare"]:
        fig, axes = plt.subplots(1, 2, figsize=(11, 4))
        sns.histplot(clean[col], kde=True, ax=axes[0], bins=30)
        axes[0].set_title(f"{col} — histogram")
        sns.boxplot(x=clean[col], ax=axes[1])
        axes[1].set_title(f"{col} — box plot")
        path = savefig(f"univariate_{col}.png")
        say(f"![{col}]({path})")
        say()

    def iqr_outliers(s: pd.Series) -> tuple[int, float, float, float, float, float]:
        q1, q3 = s.quantile(0.25), s.quantile(0.75)
        iqr = q3 - q1
        low, high = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        return int(((s < low) | (s > high)).sum()), q1, q3, iqr, low, high

    say("### IQR outlier counts (outside [Q1 − 1.5×IQR, Q3 + 1.5×IQR])")
    say()
    say("| column | Q1 | Q3 | IQR | lower fence | upper fence | outliers |")
    say("|---|---|---|---|---|---|---|")
    counts = {}
    for col in ["age", "fare"]:
        n, q1, q3, iqr, low, high = iqr_outliers(clean[col])
        counts[col] = n
        say(f"| `{col}` | {q1:.3f} | {q3:.3f} | {iqr:.3f} | {low:.3f} | "
            f"{high:.3f} | **{n}** |")
    say()

    fare_mean = clean["fare"].mean()
    fare_median = clean["fare"].median()
    fare_mode = clean["fare"].mode().iloc[0]

    if fare_mean > fare_median > fare_mode:
        skew_word = "right-skewed (positively skewed)"
        order = "mean > median > mode"
    elif fare_mean < fare_median < fare_mode:
        skew_word = "left-skewed (negatively skewed)"
        order = "mean < median < mode"
    else:
        skew_word = "not cleanly ordered, so read the skewness coefficient below"
        order = (f"mean={fare_mean:.4f}, median={fare_median:.4f}, "
                 f"mode={fare_mode:.4f}")

    say("### `fare` central tendency and skew")
    say()
    say(f"- mean = **{fare_mean:.4f}**")
    say(f"- median = **{fare_median:.4f}**")
    say(f"- mode = **{fare_mode:.4f}**")
    say(f"- Pearson skewness coefficient = **{clean['fare'].skew():.4f}**")
    say()
    say(f"**Interpretation.** The ordering is `{order}`, so `fare` is "
        f"**{skew_word}**. The mean sits above the median and the mode because "
        f"a small number of very expensive first-class tickets pull the mean "
        f"up the tail, while the bulk of passengers cluster at the cheap end — "
        f"which is also why `fare` shows **{counts['fare']}** IQR outliers "
        f"against only **{counts['age']}** for `age`. Those fare \"outliers\" "
        f"are genuine luxury fares, not data errors, so they are kept rather "
        f"than trimmed; the modelling stage handles their scale with "
        f"standardisation instead.")
    say()

    # ---------------------------------------------------------------- Task 4
    say("## Task 4 — bivariate analysis")
    say()

    female = clean["sex"] == "female"
    male = clean["sex"] == "male"
    survived = clean["survived"] == 1

    overall = clean["survived"].mean()
    say(f"Overall survival rate: **{overall:.4f}** "
        f"({int(survived.sum())} of {len(clean)}).")
    say()

    say("### (a) Survival rate by sex — via boolean masking")
    say()
    say("| sex | n | survived | survival rate |")
    say("|---|---|---|---|")
    rates_sex = {}
    for label, mask in [("female", female), ("male", male)]:
        n = int(mask.sum())
        s = int((mask & survived).sum())
        rates_sex[label] = s / n
        say(f"| {label} | {n} | {s} | **{s / n:.4f}** |")
    say()

    say("### (b) Survival rate by pclass — via boolean masking")
    say()
    say("| pclass | n | survived | survival rate |")
    say("|---|---|---|---|")
    rates_class = {}
    for pc in sorted(clean["pclass"].unique()):
        mask = clean["pclass"] == pc
        n = int(mask.sum())
        s = int((mask & survived).sum())
        rates_class[int(pc)] = s / n
        say(f"| {pc} | {n} | {s} | **{s / n:.4f}** |")
    say()

    say("### (c) Survival rate by sex AND pclass — `&` combinations")
    say()
    say("| sex | pclass | n | survived | survival rate |")
    say("|---|---|---|---|---|")
    grid = {}
    for label, smask in [("female", female), ("male", male)]:
        for pc in sorted(clean["pclass"].unique()):
            mask = smask & (clean["pclass"] == pc)
            n = int(mask.sum())
            s = int((mask & survived).sum())
            grid[(label, int(pc))] = s / n if n else float("nan")
            say(f"| {label} | {pc} | {n} | {s} | **{s / n:.4f}** |")
    say()
    say(f"**Interpretation.** Sex dominates: women survived at "
        f"{rates_sex['female']:.1%} against {rates_sex['male']:.1%} for men — "
        f"a gap of roughly {abs(rates_sex['female'] - rates_sex['male']):.0%} "
        f"points that no other single variable comes close to. Class is the "
        f"clear second axis ({rates_class[1]:.1%} in first class down to "
        f"{rates_class[3]:.1%} in third). Crossing the two shows the two "
        f"effects compound rather than cancel: first-class women survived at "
        f"{grid[('female', 1)]:.1%} while third-class men survived at "
        f"{grid[('male', 3)]:.1%}, the extremes of the whole dataset. Notably "
        f"third-class women ({grid[('female', 3)]:.1%}) still outlived "
        f"first-class men ({grid[('male', 1)]:.1%}), which says the "
        f"\"women and children first\" protocol outweighed ticket price.")
    say()

    # correlation on exactly the six specified columns
    corr = clean[CORR_COLS].corr()
    plt.figure(figsize=(7, 5.5))
    sns.heatmap(corr, annot=True, fmt=".3f", cmap="coolwarm", center=0,
                square=True, linewidths=0.5)
    plt.title("Correlation matrix (6 numeric columns)")
    path = savefig("correlation_heatmap.png")

    say("### Correlation matrix — exactly six columns")
    say()
    say("Columns: `survived`, `pclass`, `age`, `sibsp`, `parch`, `fare`. "
        "The boolean-typed `adult_male` and `alone` are **excluded**: they are "
        "derived/redundant flags (directly computable from `sex`/`age` and "
        "from `sibsp` + `parch` respectively), not independent measured "
        "features, and including them would inflate the matrix with "
        "self-correlations.")
    say()
    block(corr.round(4))
    say(f"![correlation heatmap]({path})")
    say()

    # rank all off-diagonal pairs by |r|
    pairs = []
    for i, a in enumerate(CORR_COLS):
        for b in CORR_COLS[i + 1:]:
            pairs.append((a, b, corr.loc[a, b]))
    pairs.sort(key=lambda t: abs(t[2]), reverse=True)

    say("Off-diagonal pairs ranked by |r|:")
    say()
    block("\n".join(f"{a:>9} ~ {b:<9} r = {r:+.4f}   |r| = {abs(r):.4f}"
                    for a, b, r in pairs))

    EXPLANATIONS = {
        frozenset(("pclass", "fare")):
            "Ticket class and fare are two measurements of the same "
            "underlying thing — how much a passenger paid. `pclass` is coded "
            "1/2/3 with 1 as the most expensive, so the relationship is "
            "negative by construction: as the class number rises the fare "
            "falls. The fact that it is strong but not near −1 tells us fare "
            "varied a lot *within* a class (cabin, port, family bookings).",
        frozenset(("sibsp", "parch")):
            "Siblings/spouses aboard and parents/children aboard move "
            "together because they are both slices of one latent variable: "
            "family group size. A passenger travelling as a family tends to "
            "register on both counters at once, and a solo traveller on "
            "neither — which is exactly why the derived `alone` flag was "
            "excluded from this matrix as redundant.",
        frozenset(("survived", "pclass")):
            "Survival falls as the class number rises, i.e. cheaper cabins "
            "died more. Mechanically this reflects deck position — third "
            "class was berthed lowest and furthest from the boat deck — "
            "rather than any direct effect of the ticket itself.",
        frozenset(("survived", "fare")):
            "Higher fares go with higher survival, which is the same "
            "class-and-deck story seen through the price column instead of "
            "the class column; it is not an independent effect.",
        frozenset(("age", "pclass")):
            "Older passengers cluster in the upper classes, which is a "
            "wealth-accumulation effect: first-class tickets were bought by "
            "established adults, while third class carried younger migrants "
            "and families.",
        frozenset(("age", "sibsp")):
            "Younger passengers report more siblings/spouses aboard because "
            "children travelled inside family groups, while older passengers "
            "more often travelled as couples or alone.",
    }

    say("### The two strongest correlations")
    say()
    for rank, (a, b, r) in enumerate(pairs[:2], start=1):
        expl = EXPLANATIONS.get(
            frozenset((a, b)),
            "These two features move together more than any other pair in "
            "the matrix; the sign indicates the direction of the "
            "relationship.",
        )
        say(f"**{rank}. `{a}` ↔ `{b}` (r = {r:+.4f}, |r| = {abs(r):.4f}).** {expl}")
        say()
    say("Both of the top pairs are *structural* rather than causal, which is "
        "the practical takeaway for modelling: they warn that the feature set "
        "carries redundancy, so a linear model's coefficients on these columns "
        "should not be read as independent effects.")
    say()

    # ---------------------------------------------------------------- Task 5
    say("## Task 5 — multivariate data story: who survived, and why")
    say()

    # Chart 1
    plt.figure(figsize=(7, 4.5))
    sns.barplot(data=clean, x="pclass", y="survived", hue="sex", errorbar=None)
    plt.ylabel("survival rate")
    plt.title("Survival rate by class and sex")
    p1 = savefig("story_1_class_sex.png")
    say(f"### Chart 1 — survival rate by class and sex\n\n![chart1]({p1})")
    say()
    say(f"This is the spine of the whole argument. Within every class the "
        f"female bar towers over the male bar, and the gap never closes: even "
        f"third-class women ({grid[('female', 3)]:.1%}) beat first-class men "
        f"({grid[('male', 1)]:.1%}). Class then modulates the effect inside "
        f"each sex rather than overriding it. The honest reading is that sex "
        f"was the primary filter applied at the lifeboats, and class decided "
        f"how favourably you were treated once inside that filter.")
    say()

    # Chart 2
    plt.figure(figsize=(7, 4.5))
    sns.boxplot(data=clean, x="pclass", y="fare", hue="survived")
    plt.title("Fare distribution by class, split by survival")
    p2 = savefig("story_2_fare_class_survival.png")
    say(f"### Chart 2 — fare by class, split by survival\n\n![chart2]({p2})")
    say()
    say("Fare is not an independent lever. Once you condition on class the "
        "fare boxes for survivors and non-survivors overlap heavily, "
        "especially in second and third class. That tells us the raw "
        "`survived`–`fare` correlation is largely `pclass` wearing a different "
        "hat, and that a model given both columns is getting one signal twice, "
        "not two.")
    say()

    # Chart 3
    plt.figure(figsize=(8, 4.5))
    sns.histplot(data=clean, x="age", hue="survived", bins=30,
                 multiple="stack")
    plt.title("Age distribution by survival outcome")
    p3 = savefig("story_3_age_survival.png")
    say(f"### Chart 3 — age distribution by outcome\n\n![chart3]({p3})")
    say()
    child_rate = clean.loc[clean["age"] < 16, "survived"].mean()
    adult_rate = clean.loc[clean["age"] >= 16, "survived"].mean()
    say(f"Age is a weak *linear* predictor but a real *threshold* one. Across "
        f"the adult range the survived/not-survived split is roughly constant, "
        f"which is why `age` barely registers in the correlation matrix. At "
        f"the young end it flips: under-16s survived at {child_rate:.1%} "
        f"against {adult_rate:.1%} for everyone else. A linear model will "
        f"underuse this; a tree, which can cut at a threshold, will not — and "
        f"that is one reason to expect the tree-based models to edge ahead.")
    say()

    # Chart 4
    fam = clean.assign(family_size=clean["sibsp"] + clean["parch"] + 1)
    plt.figure(figsize=(7.5, 4.5))
    sns.barplot(data=fam, x="family_size", y="survived", errorbar=None)
    plt.ylabel("survival rate")
    plt.title("Survival rate by family size (sibsp + parch + 1)")
    p4 = savefig("story_4_family_size.png")
    say(f"### Chart 4 — survival rate by family size\n\n![chart4]({p4})")
    say()
    solo = fam.loc[fam["family_size"] == 1, "survived"].mean()
    small = fam.loc[fam["family_size"].between(2, 4), "survived"].mean()
    large = fam.loc[fam["family_size"] >= 5, "survived"].mean()
    say(f"Family size is non-monotonic, which is why neither `sibsp` nor "
        f"`parch` shows much correlation on its own. Solo travellers survived "
        f"at {solo:.1%}; small families of 2–4 did best at {small:.1%}; large "
        f"families of 5+ collapsed to {large:.1%}. The plausible mechanism is "
        f"that a small group could be shepherded into a boat together, while "
        f"a large group could not be kept together and would not board "
        f"separately. The engineering lesson is that the useful feature here "
        f"is a *bucketed* family size, not either raw counter.")
    say()

    # Chart 5 — pairplot
    pair = sns.pairplot(clean[CORR_COLS], hue="survived", corner=True,
                        plot_kws={"alpha": 0.45, "s": 18})
    pair.figure.suptitle("Pairwise view of the six numeric features", y=1.01)
    os.makedirs(FIG_DIR, exist_ok=True)
    pair.figure.savefig(os.path.join(FIG_DIR, "story_5_pairplot.png"), dpi=100,
                        bbox_inches="tight")
    plt.close("all")
    say("### Chart 5 — pair plot of the six numeric features\n\n"
        "![chart5](figures/story_5_pairplot.png)")
    say()
    say("Read as a whole, the pair plot shows no single numeric feature "
        "cleanly separates the two classes — the orange and blue clouds "
        "overlap everywhere. Separation only appears in combination "
        "(low `pclass` *and* high `fare`, or low `age` *and* small family), "
        "which is the argument for a non-linear model and against expecting "
        "much from any one-variable rule.")
    say()
    say("**Story in one line.** Survival was decided first by sex, then by "
        "class/deck position, with a genuine child bonus and a small-family "
        "bonus layered on top — and the numeric features encode these effects "
        "redundantly rather than independently.")
    say()

    # ---------------------------------------------------------------- Task 6
    say("## Task 6 — exploratory standardisation check (EDA stage only)")
    say()
    say("This is a **sanity check on the full cleaned frame only**. It is "
        "deliberately *not* the modelling pipeline's preprocessing: "
        "`02_modeling.py` fits its own `StandardScaler` on the training split "
        "alone, inside a `ColumnTransformer`, to avoid leaking test-set "
        "statistics into training.")
    say()

    before = clean[["age", "fare"]].agg(["mean", "std"]).round(4)
    z = clean[["age", "fare"]].apply(lambda s: (s - s.mean()) / s.std(ddof=0))
    z.columns = ["age_z", "fare_z"]
    after = z.agg(["mean", "std"]).round(4)

    say("z = (x − mean) / std, computed manually.")
    say()
    say("**Before:**")
    block(before)
    say("**After:**")
    block(after)
    say(f"Both transformed columns land at mean ≈ 0 "
        f"(`age_z` {after.loc['mean', 'age_z']:+.4f}, "
        f"`fare_z` {after.loc['mean', 'fare_z']:+.4f}) and standard "
        f"deviation ≈ 1, confirming the transform is correct. Note the *shape* "
        f"of each distribution is unchanged — `fare_z` is still right-skewed; "
        f"standardisation rescales, it does not normalise.")
    say()

    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    for ax, col in zip(axes, ["age", "fare"]):
        sns.kdeplot(clean[col], ax=ax, label="raw", fill=True, alpha=0.3)
        sns.kdeplot(z[f"{col}_z"], ax=ax, label="z-scored", fill=True, alpha=0.3)
        ax.set_title(f"{col}: before vs after standardisation")
        ax.legend()
    p6 = savefig("standardisation_before_after.png")
    say(f"![standardisation]({p6})")
    say()

    with open(REPORT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(md) + "\n")
    print(f"\n[done] report written to {REPORT}")
    print(f"[done] cleaned data written to {CSV_CLEAN}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
