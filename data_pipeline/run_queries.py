"""
Module 1, step 3: run the SQL suite and the pandas equivalence check.

Executes 6 SQL queries that collectively cover SELECT/WHERE, ORDER BY, LIMIT,
DISTINCT, IN / BETWEEN and a JOIN; reads two of them back with pd.read_sql;
and reproduces the JOIN query with pd.merge on the in-memory DataFrames,
showing the two results side by side and asserting they are equivalent.

Every query string and its output is also written to outputs/query_results.md.

Run:  python run_queries.py
"""

from __future__ import annotations

import os
import sqlite3

import pandas as pd

DB_PATH = "books.db"
CSV_PATH = "books_clean.csv"
OUT_MD = os.path.join("outputs", "query_results.md")

pd.set_option("display.width", 120)
pd.set_option("display.max_columns", 20)

# --------------------------------------------------------------------------
# The query suite. Each entry states which required clause(s) it demonstrates.
# --------------------------------------------------------------------------
QUERIES: list[tuple[str, str, str]] = [
    (
        "Q1",
        "SELECT + WHERE - in-stock books cheaper than GBP 20",
        """
        SELECT title, price_gbp, price_inr, rating
        FROM books
        WHERE in_stock = 1 AND price_gbp < 20.0;
        """,
    ),
    (
        "Q2",
        "ORDER BY + LIMIT - the 10 most expensive books in the catalogue",
        """
        SELECT title, price_gbp, price_inr
        FROM books
        ORDER BY price_gbp DESC
        LIMIT 10;
        """,
    ),
    (
        "Q3",
        "DISTINCT - the distinct star ratings present in the catalogue",
        """
        SELECT DISTINCT rating
        FROM books
        ORDER BY rating;
        """,
    ),
    (
        "Q4",
        "IN - books belonging to a chosen subset of categories",
        """
        SELECT b.title, c.category_name, b.price_inr
        FROM books AS b
        JOIN categories AS c ON c.category_id = b.category_id
        WHERE c.category_name IN ('Fiction', 'Mystery')
        ORDER BY b.price_inr DESC
        LIMIT 15;
        """,
    ),
    (
        "Q5",
        "BETWEEN - mid-priced books (GBP 20-40) rated 4 or 5",
        """
        SELECT title, price_gbp, rating
        FROM books
        WHERE price_gbp BETWEEN 20.0 AND 40.0
          AND rating BETWEEN 4 AND 5
        ORDER BY rating DESC, price_gbp ASC
        LIMIT 20;
        """,
    ),
    (
        "Q6",
        "JOIN (the equivalence query) - top-rated books per category",
        """
        SELECT c.category_name,
               b.title,
               b.rating,
               b.price_gbp,
               b.price_inr
        FROM books AS b
        INNER JOIN categories AS c
                ON c.category_id = b.category_id
        ORDER BY c.category_name ASC, b.rating DESC, b.price_gbp DESC;
        """,
    ),
]

JOIN_QUERY_ID = "Q6"


def fmt(df: pd.DataFrame, max_rows: int = 12) -> str:
    """Render a DataFrame for the markdown log, truncating long results."""
    shown = df.head(max_rows).to_string(index=False)
    if len(df) > max_rows:
        shown += f"\n... ({len(df)} rows total, first {max_rows} shown)"
    return shown


def main() -> int:
    if not os.path.exists(DB_PATH):
        raise FileNotFoundError(f"{DB_PATH} not found - run `python build_db.py` first.")

    os.makedirs("outputs", exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    lines: list[str] = [
        "# Module 1 - executed SQL queries and their output",
        "",
        "Generated by `run_queries.py`. Each query states the required SQL "
        "clause it demonstrates.",
        "",
    ]

    results: dict[str, pd.DataFrame] = {}
    try:
        for qid, description, sql in QUERIES:
            df = pd.read_sql(sql, conn)
            results[qid] = df
            print(f"\n=== {qid}: {description} ===")
            print(sql.strip())
            print(fmt(df))

            lines += [
                f"## {qid} - {description}",
                "",
                "```sql",
                sql.strip(),
                "```",
                "",
                "Output:",
                "",
                "```",
                fmt(df),
                "```",
                "",
            ]

        # ------------------------------------------------------------------
        # pd.read_sql read-back of two queries (Q2 and Q6 below; Q1..Q6 all
        # already went through pd.read_sql above, these two are called out
        # explicitly as the required read-backs).
        # ------------------------------------------------------------------
        print("\n=== pd.read_sql read-back of Q2 and Q6 ===")
        readback_q2 = pd.read_sql(QUERIES[1][2], conn)
        readback_join = pd.read_sql(
            next(q[2] for q in QUERIES if q[0] == JOIN_QUERY_ID), conn
        )
        print(f"Q2 read back: {readback_q2.shape}")
        print(f"{JOIN_QUERY_ID} read back: {readback_join.shape}")

        # ------------------------------------------------------------------
        # Same JOIN reproduced with pd.merge on in-memory DataFrames (no SQL)
        # ------------------------------------------------------------------
        books_df = pd.read_sql("SELECT * FROM books;", conn)
        categories_df = pd.read_sql("SELECT * FROM categories;", conn)

        merged = (
            pd.merge(books_df, categories_df, on="category_id", how="inner")
            .loc[:, ["category_name", "title", "rating", "price_gbp", "price_inr"]]
            .sort_values(
                ["category_name", "rating", "price_gbp"],
                ascending=[True, False, False],
                kind="mergesort",  # stable, to match SQLite's ordering
            )
            .reset_index(drop=True)
        )

        sql_join = readback_join.reset_index(drop=True)

        print("\n--- SQL JOIN (pd.read_sql) ---")
        print(fmt(sql_join))
        print("\n--- pandas merge (pd.merge) ---")
        print(fmt(merged))

        equivalent = sql_join.equals(merged)
        print(f"\n[check] SQL JOIN result == pd.merge result -> {equivalent}")

        lines += [
            "## Equivalence check: SQL `JOIN` vs `pd.merge`",
            "",
            f"The join query ({JOIN_QUERY_ID}) was read back into pandas with "
            "`pd.read_sql(...)` and independently reproduced with "
            "`pd.merge(...)` on the in-memory `books` / `categories` "
            "DataFrames (no SQL involved in the second path).",
            "",
            "### SQL result (`pd.read_sql`)",
            "",
            "```",
            fmt(sql_join),
            "```",
            "",
            "### pandas result (`pd.merge`)",
            "",
            "```",
            fmt(merged),
            "```",
            "",
            f"**`DataFrame.equals` on the two results: `{equivalent}`** "
            f"(shapes: SQL {sql_join.shape} vs merge {merged.shape})",
            "",
        ]

        assert equivalent, "pd.merge result did not match the SQL JOIN result"
    finally:
        conn.close()

    with open(OUT_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"\n[done] query log written to {OUT_MD}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
